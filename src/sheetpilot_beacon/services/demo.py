"""Reproducible demo orchestration over the repository's sample contract."""

from __future__ import annotations

import html
from dataclasses import dataclass
from pathlib import Path

from sheetpilot_beacon.adapters.exporters import (
    export_annotated_workbook,
    export_html_report,
    export_json_report,
)
from sheetpilot_beacon.adapters.samples import SAMPLE_EXPECTATIONS, generate_sample_workbooks
from sheetpilot_beacon.services.audit import Clock, audit_workbook


@dataclass(frozen=True, slots=True)
class DemoResult:
    index_path: Path
    workbook_count: int
    finding_count: int
    generated_files: tuple[Path, ...]


def run_demo(
    samples_dir: str | Path,
    output_dir: str | Path,
    *,
    clock: Clock | None = None,
) -> DemoResult:
    """Audit all three deterministic samples and build a static index."""

    sample_root = Path(samples_dir)
    destination = Path(output_dir)
    destination.mkdir(parents=True, exist_ok=True)
    required = tuple(SAMPLE_EXPECTATIONS)
    if not all((sample_root / filename).is_file() for filename in required):
        sample_root = destination / "samples"
        generate_sample_workbooks(sample_root)

    cards: list[str] = []
    generated: list[Path] = []
    finding_count = 0
    for filename in required:
        source = sample_root / filename
        report = audit_workbook(source, clock=clock)
        stem = Path(filename).stem
        html_path = export_html_report(report, destination / f"{stem}.audit.html")
        json_path = export_json_report(report, destination / f"{stem}.audit.json")
        xlsx_path = export_annotated_workbook(
            source,
            report,
            destination / f"{stem}.annotated.xlsx",
        )
        generated.extend((html_path, json_path, xlsx_path))
        finding_count += len(report.issues)
        cards.append(
            "<article>"
            f'<p class="eyebrow">{html.escape(filename)}</p>'
            f"<h2>{len(report.issues)} findings</h2>"
            f"<p>{report.metrics.formula_cell_count} formulas · "
            f"{report.metrics.dependency_edge_count} dependency edges</p>"
            f'<a href="{html.escape(html_path.name)}">Open audit report</a>'
            "</article>"
        )
    index = destination / "index.html"
    index.write_text(
        f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>SheetPilot Beacon demo</title><style>
body{{margin:0;background:#f5f7fa;color:#102a43;font:16px/1.5 Inter,Segoe UI,sans-serif}}
main{{width:min(1100px,calc(100% - 2rem));margin:auto;padding:4rem 0}}
h1{{font-size:clamp(2.4rem,7vw,5rem);line-height:1;margin:.2rem 0 1rem}}
.intro{{max-width:740px;color:#52606d}} .grid{{display:grid;
grid-template-columns:repeat(auto-fit,minmax(240px,1fr));gap:1rem;margin-top:2rem}}
article{{background:white;border:1px solid #d9e2ec;border-radius:16px;padding:1.25rem}}
.eyebrow{{color:#0f766e;font-weight:800}} a{{color:#0f766e;font-weight:700}}
</style></head><body><main><p class="eyebrow">Offline · deterministic · synthetic</p>
<h1>Workbook risk,<br>mapped clearly.</h1>
<p class="intro">Three licensed sample workbooks, fifteen seeded findings,
and reports generated by the same core used by the CLI and Streamlit app.</p>
<div class="grid">{"".join(cards)}</div></main></body></html>""",
        encoding="utf-8",
    )
    generated.append(index)
    return DemoResult(
        index_path=index,
        workbook_count=len(required),
        finding_count=finding_count,
        generated_files=tuple(generated),
    )
